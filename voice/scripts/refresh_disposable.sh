#!/usr/bin/env bash
# Refreshes the list of throwaway email domains (app/data/disposable_domains.txt) that verify.py and the
# website's contact form refuse. Source: github.com/disposable-email-domains/disposable-email-domains.
set -euo pipefail
cd "$(dirname "$0")/.."
curl -sfL https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf -o app/data/disposable_domains.txt
node -e 'const fs=require("fs");const d=fs.readFileSync("app/data/disposable_domains.txt","utf8").split("\n").map(s=>s.trim().toLowerCase()).filter(s=>s&&!s.startsWith("#"));fs.writeFileSync("../lib/disposable-domains.js","// Generated by voice/scripts/refresh_disposable.sh from github.com/disposable-email-domains/disposable-email-domains. Do not edit.\nexport const DISPOSABLE = new Set("+JSON.stringify(d)+");\n")'
wc -l app/data/disposable_domains.txt
